export function getMockGatewayLogs(params?: Record<string, string | number | undefined>): {
  logs: GatewayLogEntry[];
  total: number;
  next_cursor: string | null;
} {
  let logs = [...MOCK_GATEWAY_LOGS];

  if (params?.status && params.status !== "all") {
    logs = logs.filter((l) => l.status === params.status);
  }

  if (params?.provider && params.provider !== "all") {
    logs = logs.filter((l) => l.provider === params.provider);
  }

  if (params?.search) {
    const q = String(params.search).toLowerCase().trim();
    logs = logs.filter(
      (l) =>
        (l.route_name ?? "").toLowerCase().includes(q) ||
        (l.requested_model ?? l.model ?? "").toLowerCase().includes(q) ||
        (l.served_model ?? l.model ?? "").toLowerCase().includes(q) ||
        (l.request_id ?? l.id).toLowerCase().includes(q) ||
        (l.provider ?? "").toLowerCase().includes(q),
    );
  }

  const limit = Math.min(100, Math.max(1, Number(params?.limit ?? 50)));
  const offset = Number(params?.cursor ?? 0) || 0;
  const slice = logs.slice(offset, offset + limit);

  return {
    logs: slice,
    total: logs.length,
    next_cursor: offset + limit < logs.length ? String(offset + limit) : null,
  };
}
